using System.Text;

namespace IlsOntVote.Web.Services;

/// <summary>
/// Prompt prêt à coller dans l'assistant d'IA de son choix (bouton « Résumer avec une IA »). Le site n'appelle AUCUNE IA lui-même (pas de clé, pas de coût) :
/// il prépare un texte qui impose la neutralité et les sources, et c'est le lecteur qui l'envoie, ou non, à l'outil qu'il choisit. Le prompt ne contient que des
/// données publiques de la page (titre, date, résultat, liens officiels), jamais de donnée sur le lecteur.
/// </summary>
public static class PromptResume
{
    /// <summary>
    /// Construit le prompt. <paramref name="objet"/> : « scrutin », « loi »… (déjà dans la langue voulue) ; <paramref name="faits"/> : lignes de faits tirées de la
    /// base ; <paramref name="liens"/> : adresses de la page et des sources officielles. Reste court : les adresses de pré-remplissage des assistants ont une longueur maximale.
    /// </summary>
    public static string Construire(bool en, string objet, string titre, IEnumerable<string> faits, IEnumerable<string> liens)
    {
        var sb = new StringBuilder();
        if (en)
            sb.Append($"Summarize this parliamentary {objet} in plain English, in 5 to 8 lines. Stay strictly neutral and factual: do not attribute intentions or opinions to elected members and do not take sides. ")
              .Append("Rely on the official sources listed below; if something is missing or uncertain, say so instead of guessing. ")
              .Append("End by stating that this summary was generated by an AI and is not official.\n\n");
        else
            sb.Append($"Résume ce {objet} parlementaire en français, en 5 à 8 lignes. Reste strictement neutre et factuel : ne prête ni intention ni opinion aux élus et ne prends pas parti. ")
              .Append("Appuie-toi sur les sources officielles ci-dessous ; si une information manque ou est incertaine, dis-le au lieu de la deviner. ")
              .Append("Termine en précisant que ce résumé est généré par une IA et n'est pas officiel.\n\n");
        sb.Append(en ? "Title: " : "Titre : ").Append(titre).Append('\n');
        foreach (var f in faits.Where(x => !string.IsNullOrWhiteSpace(x))) sb.Append("- ").Append(f).Append('\n');
        sb.Append(en ? "Sources:\n" : "Sources :\n");
        foreach (var l in liens.Where(x => !string.IsNullOrWhiteSpace(x))) sb.Append("- ").Append(l).Append('\n');
        return sb.ToString().TrimEnd();
    }
}
