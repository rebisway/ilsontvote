using System.Text;

namespace IlsOntVote.Web.Services;

/// <summary>
/// Prompt prêt à coller dans l'assistant d'IA de son choix (bouton « Résumer avec une IA »). Le site n'appelle AUCUNE IA lui-même (pas de clé, pas de coût) :
/// il prépare un texte qui impose la neutralité et les sources, et c'est le lecteur qui l'envoie, ou non, à l'outil qu'il choisit. Le prompt ne contient que des
/// données publiques de la page (titre du texte, liens officiels), jamais de donnée sur le lecteur.
/// </summary>
public static class PromptResume
{
    /// <summary>
    /// Construit le prompt. Demande le résumé du CONTENU du texte (ce que la loi prévoit), pas des métadonnées ni des votes : aucun chiffre de scrutin n'est donné à l'IA,
    /// seulement le titre et les adresses où le texte lui-même se lit. Longueur libre (un texte de loi ne se résume pas en 8 lignes). Si l'assistant ne peut pas lire
    /// les adresses, il doit le dire au lieu de résumer le titre ou d'inventer (constaté : sans cette consigne, les IA résumaient les métadonnées).
    /// </summary>
    public static string Construire(bool en, string titre, IEnumerable<string> liens)
    {
        var sb = new StringBuilder();
        if (en)
            sb.Append("I want to understand the CONTENT of the following bill or legislative text: what it actually provides for. I do not want a summary of the votes, the dates or the metadata. ")
              .Append("Read the text itself at the addresses below (bill text, explanatory notes, legislative file). Then write a detailed, structured summary: the purpose and context given in the explanatory notes; the main measures grouped by theme, following the text's own parts, chapters and articles; what changes compared with existing law; and when the provisions take effect. ")
              .Append("Take the length that is needed to be faithful: do not limit yourself to a few lines. Cite article numbers where useful. ")
              .Append("Stay strictly neutral and factual: no judgement, no opinion, no intentions attributed to elected members. ")
              .Append("If you cannot open or read the text, say so clearly instead of guessing or summarizing the title alone. ")
              .Append("End by stating that this summary was generated by an AI and is not official.\n\n");
        else
            sb.Append("Je veux comprendre le CONTENU du texte de loi suivant : ce qu'il prévoit réellement. Je ne veux pas un résumé des votes, des dates ni des métadonnées. ")
              .Append("Lis le texte lui-même aux adresses ci-dessous (texte déposé ou adopté, exposé des motifs, dossier législatif). Rédige ensuite un résumé détaillé et structuré : l'objet et le contexte donnés par l'exposé des motifs ; les mesures principales regroupées par thème, en suivant les titres, chapitres et articles du texte ; ce qui change par rapport au droit existant ; la date d'entrée en vigueur des dispositions. ")
              .Append("Prends la longueur nécessaire pour rester fidèle : ne te limite pas à quelques lignes. Cite les numéros d'articles quand c'est utile. ")
              .Append("Reste strictement neutre et factuel : aucun jugement, aucune opinion, aucune intention prêtée aux élus. ")
              .Append("Si tu ne peux pas ouvrir ou lire le texte, dis-le clairement au lieu de deviner ou de résumer le seul titre. ")
              .Append("Termine en précisant que ce résumé est généré par une IA et n'est pas officiel.\n\n");
        sb.Append(en ? "Text: " : "Texte : ").Append(titre).Append('\n');
        sb.Append(en ? "Sources:\n" : "Sources :\n");
        foreach (var l in liens.Where(x => !string.IsNullOrWhiteSpace(x)).Distinct()) sb.Append("- ").Append(l).Append('\n');
        return sb.ToString().TrimEnd();
    }
}
